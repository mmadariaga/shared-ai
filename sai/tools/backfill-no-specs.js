#!/usr/bin/env node
'use strict';

// Deterministic no-specs backfill of the Direct Build route: when a verified Ready to Propose block
// declares `**Specs**: none — <reason>`, the two drafts (`.openspec.yaml`, `proposal.md`) derive from the
// block alone, so no backfill worker composes them.
//
// compose --block-file <path> --block-hash <sha256> --change-name <name> --transfer-dir <dir>
//         [--backlog-origin <url>] [--explore-origin "<harness> <id>[, <id>...]"] [--created YYYY-MM-DD] [--cwd root]
//   stdout: one JSON object. `ok: true` carries `draft_references` ({path, sha256, destination}, one per
//   draft, the files written with transfer.js put) and `warnings`. `ok: false` with `eligible: false`
//   means the change follows the worker route; any other `ok: false` is an error.
const fs = require('node:fs');
const path = require('node:path');
const { verifyBlockFile, detect, STRICT_FIELDS } = require('./ready-to-propose');
const { exploreOriginHarness } = require('./openspec-yaml');
const transfer = require('./transfer');

const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const LABELS = new Set(STRICT_FIELDS.map(field => field.label));
const FIELD_LINE = /^\*\*(.+?)\*\*:[ \t]*(.*)$/;
const BANNER = '> **⚠ POST-HOC RECORD** — This proposal was backfilled after implementation against a user-supplied statement of intent. It describes a decision already made, not one being proposed.';
const OUT_OF_SCOPE = 'Out of scope: design.md, tasks.md, implementation.md — not generated by /sai-backfill';

/** The fields of one block: label to {inline, body}, `body` being the lines under the label, edges trimmed. */
function parseFields(text) {
  const fields = new Map();
  let current = null;
  for (const line of text.split('\n')) {
    if (line.trim() === '---') break;
    const match = FIELD_LINE.exec(line);
    if (match && LABELS.has(match[1])) {
      current = { inline: match[2].trim(), lines: [] };
      if (!fields.has(match[1])) fields.set(match[1], current);
      continue;
    }
    if (current) current.lines.push(line);
  }
  for (const field of fields.values()) {
    const lines = [...field.lines];
    while (lines.length && lines[0].trim() === '') lines.shift();
    while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();
    field.body = lines.join('\n');
    delete field.lines;
  }
  return fields;
}

/** The list items of a field body, each with its continuation lines, verbatim; `- None` is no item. */
function items(body = '') {
  const out = [];
  for (const line of body.split('\n')) {
    if (line.startsWith('- ')) out.push(line.trimEnd());
    else if (out.length && line.trim() !== '') out[out.length - 1] += `\n${line.trimEnd()}`;
  }
  return out.filter(item => item !== '- None');
}

/** The repository path of a Research Leads entry: its first token, without backticks or a `:line` suffix. */
function leadPath(item) {
  const token = item.slice(2).trim().split(/\s+/)[0].replace(/[`,]/g, '').replace(/:\d+(?:-\d+)?$/, '');
  return token.includes('/') || /\.[A-Za-z0-9]+$/.test(token) ? token : null;
}

function localDate(now = new Date()) {
  const pad = value => String(value).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function origins(block, options, warnings) {
  let backlog = block.backlog_origin;
  if (options['backlog-origin']) {
    try {
      const identity = require('./backlog-slice-identity');
      const value = options['backlog-origin'];
      if (identity.normalize(value, identity.platformFor(value)) !== value) throw new Error('noncanonical');
      if (backlog && backlog !== value) warnings.push(`Backlog origin conflict: the block carries ${backlog}; kept the supplied ${value}`);
      backlog = value;
    } catch { warnings.push('The supplied backlog origin is not a canonical issue URL and was left out'); }
  }
  let explore = block.explore_origin;
  if (options['explore-origin']) {
    const ids = options['explore-origin'].split(',').map(part => part.trim().split(' ').pop()).filter(Boolean);
    if (ids.length && ids.every(id => exploreOriginHarness(id))) {
      if (explore.length && explore.join() !== ids.join()) warnings.push('Explore origin conflict: the block and the supplied value differ; kept the supplied value');
      explore = ids;
    } else warnings.push('The supplied explore origin has no valid session id and was left out');
  }
  return { backlog, explore };
}

function metadata({ created, backlog, explore }) {
  return [
    'schema: sai-workflow',
    `created: ${created}`,
    'backfilled: true',
    'prior_intent: true',
    'skip_specs: true',
    ...(backlog ? [`backlog_origin: ${backlog}`] : []),
    ...(explore.length ? [`explore_origin: [${explore.join(', ')}]`] : []),
    '',
  ].join('\n');
}

function proposal(fields) {
  const field = label => fields.get(label);
  const list = label => items(field(label)?.body);
  const whatChanges = [`- ${field('What').inline}`, ...list('Implementation Details').map(item => `- ${item.slice(2)}`)];
  const section = (title, entries) => entries.length ? [title, ...entries, ''] : [];
  const leads = [...new Set(list('Research Leads').map(leadPath).filter(Boolean))];
  const notes = field('Request Additional Notes');
  const notesText = notes ? [notes.inline, notes.body].filter(Boolean).join('\n') : '';
  const decisions = list('Decisions & Rationale');
  return [
    BANNER,
    '',
    '## Why',
    '',
    field('Why').inline,
    '',
    '## What Changes',
    '',
    ...whatChanges,
    '',
    '## Capabilities',
    '',
    '### New Capabilities',
    '- None',
    '',
    '### Modified Capabilities',
    '- None',
    '',
    '## Impact',
    '',
    ...section('Capabilities in scope of this change:', list('Capabilities in scope')),
    ...section('Edge cases agreed for this change:', list('Edge Cases')),
    ...section('Key constraints of this change:', list('Key constraints')),
    OUT_OF_SCOPE,
    '',
    '## Proposal Research Documentation',
    '',
    '**Local files**:',
    ...(leads.length ? leads.map(lead => `- ${lead}`) : ['- None']),
    '',
    '**External URLs**:',
    '- None',
    ...(notesText ? ['', '## Request Additional Notes', '', notesText] : []),
    ...(decisions.length ? ['', '## Additional Notes', '', 'Decisions & Rationale agreed for this change:', ...decisions] : []),
    '',
  ].join('\n');
}

function specsFiles(cwd, name) {
  const dir = path.join(cwd, 'openspec', 'changes', name, 'specs');
  const walk = current => {
    let entries;
    try { entries = fs.readdirSync(current, { withFileTypes: true }); } catch (error) { if (error.code === 'ENOENT') return []; throw error; }
    return entries.flatMap(entry => entry.isDirectory() ? walk(path.join(current, entry.name)) : [entry.name]);
  };
  return walk(dir);
}

function compose(options) {
  const { 'block-file': blockFile, 'block-hash': blockHash, 'change-name': name, 'transfer-dir': dir } = options;
  const cwd = options.cwd || process.cwd();
  if (!blockFile || !blockHash || !name || !dir) throw new Error('Expected --block-file, --block-hash, --change-name, and --transfer-dir');
  if (!NAME.test(name)) throw new Error('Invalid change name');
  const created = options.created || localDate();
  if (!DATE.test(created)) throw new Error('--created must be YYYY-MM-DD');
  const text = verifyBlockFile(blockFile, blockHash);
  const verdict = detect(text, 'strict');
  const block = verdict.blocks[0];
  if (!verdict.ok || !block) throw new Error(`Block is not a valid Ready to Propose block: ${JSON.stringify(verdict.violations)}`);
  if (block.name !== name) throw new Error(`The block names ${block.name}, not ${name}`);
  const fields = parseFields(text);
  const specs = fields.get('Specs')?.inline ?? '';
  if (!/^none\s*—\s*\S/.test(specs)) return { ok: false, eligible: false, reason: 'The block does not declare **Specs**: none — <reason>' };
  if (specsFiles(cwd, name).length) return { ok: false, eligible: false, reason: `openspec/changes/${name}/specs/ already holds files` };
  const warnings = [];
  const drafts = [
    ['.openspec.yaml', metadata({ created, ...origins(block, options, warnings) })],
    ['proposal.md', proposal(fields)],
  ];
  const draft_references = drafts.map(([relative, content]) => ({
    ...transfer.put(dir, relative, Buffer.from(content, 'utf8')),
    destination: `openspec/changes/${name}/${relative}`,
  }));
  return { ok: true, eligible: true, change_name: name, draft_references, warnings };
}

function main(argv) {
  const [command, ...args] = argv;
  const options = {};
  for (let i = 0; i < args.length; i += 2) {
    const flag = args[i];
    if (!['--block-file', '--block-hash', '--change-name', '--transfer-dir', '--backlog-origin', '--explore-origin', '--created', '--cwd'].includes(flag) || !args[i + 1]) throw new Error('Expected compose --block-file <path> --block-hash <sha256> --change-name <name> --transfer-dir <dir> [--backlog-origin <url>] [--explore-origin <value>] [--created YYYY-MM-DD] [--cwd root]');
    options[flag.slice(2)] = args[i + 1];
  }
  if (command !== 'compose') throw new Error('Expected the compose sub-command');
  return compose(options);
}

if (require.main === module) {
  let result;
  try { result = main(process.argv.slice(2)); } catch (error) { result = { ok: false, error: error.message }; }
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  process.exitCode = result.ok ? 0 : 1;
}
module.exports = { compose, main, parseFields, BANNER, OUT_OF_SCOPE };
