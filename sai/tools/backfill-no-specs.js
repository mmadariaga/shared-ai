#!/usr/bin/env node
'use strict';

// Deterministic no-specs backfill of the Direct Build route: when a verified change document
// declares `Specs: none — <reason>` in its `## Change` section, the two drafts (`.openspec.yaml`,
// `proposal.md`) derive from the document alone, so no backfill worker composes them.
//
// compose --document-file <path> --document-hash <sha256> --change-name <name> --transfer-dir <dir>
//         [--backlog-origin <url>] [--explore-origin "<harness> <id>[, <id>...]"] [--created YYYY-MM-DD] [--cwd root]
//   stdout: one JSON object. `ok: true` carries `draft_references` ({path, sha256, destination}, one per
//   draft, the files written with transfer.js put) and `warnings`. `ok: false` with `eligible: false`
//   means the change follows the worker route; any other `ok: false` is an error.
const fs = require('node:fs');
const path = require('node:path');
const { verifyDocumentFile, checkDocument, parseIssueSections, sectionMap } = require('./change-document');
const { exploreOriginHarness } = require('./openspec-yaml');
const transfer = require('./transfer');
const usageKit = require('./usage');

const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const DATE = /^\d{4}-\d{2}-\d{2}$/;
const BANNER = '> **⚠ POST-HOC RECORD** — This proposal was backfilled after implementation against a user-supplied statement of intent. It describes a decision already made, not one being proposed.';
const OUT_OF_SCOPE = 'Out of scope: design.md, tasks.md, implementation.md — not generated by /sai-backfill';

/** The sections of one document: lowercase heading to its body lines, edges trimmed. */
function parseSections(text) {
  const sections = new Map();
  for (const [key, body] of sectionMap(parseIssueSections(text))) {
    const lines = [...body];
    while (lines.length && lines[0].trim() === '') lines.shift();
    while (lines.length && lines[lines.length - 1].trim() === '') lines.pop();
    sections.set(key, lines.join('\n'));
  }
  return sections;
}

/** The list items of a section body, each with its continuation lines, verbatim; `- None` is no item. */
function items(body = '') {
  const out = [];
  for (const line of body.split('\n')) {
    if (line.startsWith('- ')) out.push(line.trimEnd());
    else if (out.length && line.trim() !== '') out[out.length - 1] += `\n${line.trimEnd()}`;
  }
  return out.filter(item => !/^- (?:none|n\/a)\.?$/i.test(item));
}

/** The repository path of a Research leads entry: its first token, without backticks or a `:line` suffix. */
function leadPath(item) {
  const token = item.slice(2).trim().split(/\s+/)[0].replace(/[`,]/g, '').replace(/:\d+(?:-\d+)?$/, '');
  return token.includes('/') || /\.[A-Za-z0-9]+$/.test(token) ? token : null;
}

function localDate(now = new Date()) {
  const pad = value => String(value).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

function origins(change, options, warnings) {
  let backlog = change.backlog_origin;
  if (options['backlog-origin']) {
    try {
      const identity = require('./backlog-slice-identity');
      const value = options['backlog-origin'];
      if (identity.normalize(value, identity.platformFor(value)) !== value) throw new Error('noncanonical');
      if (backlog && backlog !== value) warnings.push(`Backlog origin conflict: the document carries ${backlog}; kept the supplied ${value}`);
      backlog = value;
    } catch { warnings.push('The supplied backlog origin is not a canonical issue URL and was left out'); }
  }
  let explore = change.explore_origin;
  if (options['explore-origin']) {
    const ids = options['explore-origin'].split(',').map(part => part.trim().split(' ').pop()).filter(Boolean);
    if (ids.length && ids.every(id => exploreOriginHarness(id))) {
      if (explore.length && explore.join() !== ids.join()) warnings.push('Explore origin conflict: the document and the supplied value differ; kept the supplied value');
      explore = ids;
    } else warnings.push('The supplied explore origin has no valid session id and was left out');
  }
  return { backlog, explore };
}

function metadata({ created, backlog, explore }) {
  return [
    'schema: sai-workflow',
    `created: ${created}`,
    'backfilled: true',
    'prior_intent: true',
    'skip_specs: true',
    ...(backlog ? [`backlog_origin: ${backlog}`] : []),
    ...(explore.length ? [`explore_origin: [${explore.join(', ')}]`] : []),
    '',
  ].join('\n');
}

function proposal(sections) {
  const body = key => sections.get(key) ?? '';
  const list = key => items(body(key));
  const oneLine = key => body(key).split('\n').map(line => line.trim()).filter(Boolean).join(' ');
  const whatChanges = [`- ${oneLine('goal')}`, ...list('implementation notes').map(item => `- ${item.slice(2)}`)];
  const section = (title, entries) => entries.length ? [title, ...entries, ''] : [];
  const leads = [...new Set(list('research leads').map(leadPath).filter(Boolean))];
  const notesText = body('additional notes');
  const decisions = list('decisions');
  return [
    BANNER,
    '',
    '## Why',
    '',
    oneLine('problem'),
    '',
    '## What Changes',
    '',
    ...whatChanges,
    '',
    '## Capabilities',
    '',
    '### New Capabilities',
    '- None',
    '',
    '### Modified Capabilities',
    '- None',
    '',
    '## Impact',
    '',
    ...section('Capabilities in scope of this change:', list('capabilities')),
    ...section('Edge cases agreed for this change:', list('edge cases')),
    ...section('Scope of this change:', list('scope')),
    ...section('Non-goals of this change:', list('non-goals')),
    OUT_OF_SCOPE,
    '',
    '## Proposal Research Documentation',
    '',
    '**Local files**:',
    ...(leads.length ? leads.map(lead => `- ${lead}`) : ['- None']),
    '',
    '**External URLs**:',
    '- None',
    ...(notesText ? ['', '## Request Additional Notes', '', notesText] : []),
    ...(decisions.length ? ['', '## Additional Notes', '', 'Decisions agreed for this change:', ...decisions] : []),
    '',
  ].join('\n');
}

function specsFiles(cwd, name) {
  const dir = path.join(cwd, 'openspec', 'changes', name, 'specs');
  const walk = current => {
    let entries;
    try { entries = fs.readdirSync(current, { withFileTypes: true }); } catch (error) { if (error.code === 'ENOENT') return []; throw error; }
    return entries.flatMap(entry => entry.isDirectory() ? walk(path.join(current, entry.name)) : [entry.name]);
  };
  return walk(dir);
}

function compose(options) {
  const { 'document-file': documentFile, 'document-hash': documentHash, 'change-name': name, 'transfer-dir': dir } = options;
  const cwd = options.cwd || process.cwd();
  if (!documentFile || !documentHash || !name || !dir) throw new Error('Expected --document-file, --document-hash, --change-name, and --transfer-dir');
  if (!NAME.test(name)) throw new Error('Invalid change name');
  const created = options.created || localDate();
  if (!DATE.test(created)) throw new Error('--created must be YYYY-MM-DD');
  const text = verifyDocumentFile(documentFile, documentHash);
  const check = checkDocument(text);
  if (!check.ok || !check.name) throw new Error(`Document is not a valid change document: ${JSON.stringify(check.violations)}`);
  if (check.name !== name) throw new Error(`The document names ${check.name}, not ${name}`);
  if (!check.change.specs_none) return { ok: false, eligible: false, reason: 'The document does not declare Specs: none — <reason>' };
  if (specsFiles(cwd, name).length) return { ok: false, eligible: false, reason: `openspec/changes/${name}/specs/ already holds files` };
  const warnings = [];
  const drafts = [
    ['.openspec.yaml', metadata({ created, ...origins(check.change, options, warnings) })],
    ['proposal.md', proposal(parseSections(text))],
  ];
  const draft_references = drafts.map(([relative, content]) => ({
    ...transfer.put(dir, relative, Buffer.from(content, 'utf8')),
    destination: `openspec/changes/${name}/${relative}`,
  }));
  return { ok: true, eligible: true, change_name: name, draft_references, warnings };
}

const BN = 'node sai/tools/backfill-no-specs.js';

const USAGE = {
  subcommands: {
    compose: {
      usage: [`${BN} compose --document-file <path> --document-hash <sha256> --change-name <name> --transfer-dir <dir> [--backlog-origin <url>] [--explore-origin <value>] [--created <YYYY-MM-DD>] [--cwd <root>]`],
      notes: [
        'Derives .openspec.yaml and proposal.md from a verified change document that declares `Specs: none` and prints one JSON object. Exit codes: 0 = composed;',
        '1 = not eligible or failed; 2 = usage error. --backlog-origin and --explore-origin only carry an existing origin.',
      ],
      examples: [`${BN} compose --document-file document.md --document-hash 0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef --change-name my-change --transfer-dir /path/to/transfer-dir --cwd /path/to/project`],
      flags: { '--document-file': true, '--document-hash': true, '--change-name': true, '--transfer-dir': true, '--backlog-origin': true, '--explore-origin': true, '--created': true, '--cwd': true },
      required: ['--document-file', '--document-hash', '--change-name', '--transfer-dir'],
    },
  },
};

function main(argv) {
  const [command, ...args] = argv;
  const options = {};
  for (let i = 0; i < args.length; i += 2) {
    const flag = args[i];
    if (!['--document-file', '--document-hash', '--change-name', '--transfer-dir', '--backlog-origin', '--explore-origin', '--created', '--cwd'].includes(flag) || !args[i + 1]) throw new Error('Expected compose --document-file <path> --document-hash <sha256> --change-name <name> --transfer-dir <dir> [--backlog-origin <url>] [--explore-origin <value>] [--created YYYY-MM-DD] [--cwd root]');
    options[flag.slice(2)] = args[i + 1];
  }
  if (command !== 'compose') throw new Error('Expected the compose sub-command');
  return compose(options);
}

// A usage error exits 2; a document that is not eligible or a failed composition (a domain failure) exits 1.
function cli(argv) {
  const guarded = usageKit.handle(USAGE, argv, {
    json: info => (info.help ? { usage: info.usage, examples: info.examples } : { ok: false, error: info.cause, usage: info.usage, examples: info.examples }),
  });
  if (guarded !== null) return guarded;
  let result;
  try { result = main(argv); } catch (error) { result = { ok: false, error: error.message }; }
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
  return result.ok ? 0 : 1;
}

if (require.main === module) process.exitCode = cli(process.argv.slice(2));
module.exports = { compose, main, parseSections, BANNER, OUT_OF_SCOPE, USAGE };
